#!/usr/bin/env python3
"""Refresh trusted Cloudflare networks for VueSmile's nginx virtual host.

No arguments; requires root, network access and nginx with the real-IP module.
Writes two config files only after validating Cloudflare's public IP API response.
Returns exit status 0 on success; raises an error without reloading nginx on failure.
Example: sudo python3 ops/update-cloudflare-networks.py && sudo nginx -t
Review the diff/configuration and reload nginx separately after a successful check.
Only the VueSmile virtual host includes these settings; other sites are unaffected.
"""
import ipaddress
import json
from pathlib import Path
import urllib.request


def main():
    """Fetch public CIDRs and write the trusted-header and original-peer configs."""
    with urllib.request.urlopen('https://api.cloudflare.com/client/v4/ips', timeout=30) as response:
        payload = json.load(response)
    if not payload.get('success'):
        raise RuntimeError('Cloudflare did not return a valid network list')
    ranges = payload['result']['ipv4_cidrs'] + payload['result']['ipv6_cidrs']
    networks = [str(ipaddress.ip_network(value)) for value in ranges]
    if len(networks) < 15:
        raise RuntimeError('Refusing an unexpectedly small Cloudflare network list')
    realip = '# Generated by ops/update-cloudflare-networks.py; trust only Cloudflare headers.\n'
    realip += ''.join(f'set_real_ip_from {network};\n' for network in networks)
    realip += 'real_ip_header CF-Connecting-IP;\nreal_ip_recursive on;\n'
    # $realip_remote_addr retains the TCP peer even after the visitor IP is restored.
    peers = '# Original peers allowed to reach VueSmile PHP; loopback is for local health checks.\n'
    peers += 'geo $realip_remote_addr $vuesmile_cloudflare_peer {\n    default 0;\n    127.0.0.1/32 1;\n    ::1/128 1;\n'
    peers += ''.join(f'    {network} 1;\n' for network in networks) + '}\n'
    Path('/etc/nginx/snippets/vuesmile-cloudflare-realip.conf').write_text(realip)
    Path('/etc/nginx/conf.d/31-vuesmile-origin-peers.conf').write_text(peers)
    print(f'Updated {len(networks)} validated Cloudflare network ranges.')


if __name__ == '__main__':
    main()
